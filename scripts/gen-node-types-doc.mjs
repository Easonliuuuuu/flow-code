#!/usr/bin/env node
/**
 * Generates docs/node-types.md from the node type registry — the same data
 * `flow-code node-types` prints, so the reference cannot drift from the code
 * that defines it. Run `npm run docs:node-types` after changing a node type.
 *
 * With `--check` it regenerates in memory and fails if the committed file is
 * stale, which is how CI catches a registry change that skipped the docs.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const distEntry = join(repoRoot, 'dist', 'registry', 'index.js');
const outputPath = join(repoRoot, 'docs', 'node-types.md');

if (!existsSync(distEntry)) {
  console.error('gen-node-types-doc: dist/ not built. Run `npm run build` first.');
  process.exit(1);
}

const { listNodeTypes } = await import(distEntry);

/** Fence a value in the shortest backtick run that can contain it. */
function code(value) {
  const longest = (String(value).match(/`+/g) ?? []).reduce((n, run) => Math.max(n, run.length), 0);
  const fence = '`'.repeat(longest + 1);
  const pad = longest > 0 ? ' ' : '';
  return `${fence}${pad}${value}${pad}${fence}`;
}

function session(type) {
  if (!type.agentDriven) {
    return type.hasOptionalAgentStep
      ? 'no — deterministic, with an optional read-only agent step'
      : 'no';
  }
  return type.interactive ? 'yes, interactive (can wait for you)' : 'yes, headless';
}

function render(types) {
  const lines = [
    '<!-- Generated by scripts/gen-node-types-doc.mjs. Do not edit by hand. -->',
    '<!-- Regenerate with: npm run docs:node-types -->',
    '',
    '# Node type reference',
    '',
    'Every built-in node type, its capabilities, and the shape of its `config` and',
    'recorded output. `flow-code node-types` prints the same reference in your terminal.',
    '',
    'A node type is defined by the triple (capability set, role prompt, output schema).',
    'Capabilities are compiled into enforced session restrictions by the harness — a node',
    'without `edit` cannot write files, whatever its instructions say.',
    '',
    '| Type | Purpose | Agent session |',
    '| --- | --- | --- |',
  ];

  for (const type of types) {
    const purpose = type.description.split('. ')[0].replace(/\.$/, '');
    lines.push(`| [\`${type.id}\`](#${type.id}) | ${purpose} | ${session(type)} |`);
  }

  for (const type of types) {
    lines.push('', `## \`${type.id}\``, '', `**${type.displayName}.** ${type.description}`, '');
    const caps = type.capabilities.length > 0 ? type.capabilities.map(code).join(', ') : '_none_';
    lines.push(`- **Capabilities:** ${caps}`);
    lines.push(`- **Agent session:** ${session(type)}`);
    lines.push(`- **Model field:** ${type.hasModelField ? 'yes — settable per node, or with `m` mid-run' : 'no'}`);
    lines.push(`- **Config:** ${code(type.configSummary)}`);
    lines.push(`- **Output:** ${code(type.outputSummary)}`);
    if (type.failsWhen) {
      lines.push('- **Fails on:** its own output verdict — a `fail` verdict errors the node, which is what a loop-back into it routes on.');
    }
    if (type.contextTransparent) {
      lines.push('- **Context:** transparent — forwards its dependencies\' outputs downstream, so inserting it into a graph does not sever the context chain across it.');
    }
  }

  lines.push(
    '',
    '---',
    '',
    'See [workflow-reference.md](workflow-reference.md) for how nodes are wired together,',
    'and [skills.md](skills.md) for attaching custom instructions to a node.',
    '',
  );
  return lines.join('\n');
}

const generated = render(listNodeTypes());
const check = process.argv.includes('--check');

if (check) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (current !== generated) {
    console.error(
      'gen-node-types-doc: docs/node-types.md is out of date with the node type registry.\n' +
        'Run `npm run docs:node-types` and commit the result.',
    );
    process.exit(1);
  }
  console.log('gen-node-types-doc: docs/node-types.md is up to date.');
} else {
  writeFileSync(outputPath, generated);
  console.log(`gen-node-types-doc: wrote ${outputPath}`);
}
